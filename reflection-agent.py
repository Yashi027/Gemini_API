from google import genai
from dotenv import load_dotenv
import os

load_dotenv()

API_KEY = os.getenv("GEMINI_API_KEY")

if not API_KEY:
    raise ValueError("Gemini api key not found")

client = genai.Client(
    api_key=API_KEY
)

class Reflection_agent:
    """
    Reflection Agent
    Responsibilities:
    1. Review the first draft of the code generated by the AI agent.
    2. Identify any potential issues, bugs, or areas for improvement in the code.
    3. Generate improved code based on the identified issues and best practices.
    """

    def __init__(self):
        pass

    def review_draft(self,draft):
        print("===== Reviewing Draft =====")
        prompt = f"""
            You are a senior AI reviewer.
            Review the following career report.
            Career report : {draft}

            Evaluate the report on:
            1. Accuracy
            2. Completeness
            3. Practicality and Clarity
            4. Missing Information
            5. Actionable Advice

            Rules:
            - Do not rewrite the report.
            - Only provide feedback.
            - Mention strengths.
            - Mention weakness.
            - Suggest Improvements.
        """

        response = client.models.generate_content(
                        model="gemini-3.1-flash-lite",
                        contents=prompt
                    )

        print("===================== Reviewer Feedback ======================")
        print(response.text)

    def improve_draft(self, draft, feedback):
        print("===== Improving Draft =====")

        prompt = f"""
            You are a expert AI Career Consultant.
            Original report : {draft}
            Reviewer feedback: {feedback}
            Your task: Rewrite the report
            Requirements:
            - Add missing information
            - Make recommendation more practical
            - Make roadmap more actionable

        """

        response = client.models.generate_content(
                        model="gemini-3.1-flash-lite",
                        contents=prompt
                    )

        print("===================== Improved Report ======================")
        print(response.text)

    def reflect(self,draft):
        "Draft -> Review -> Improve -> Final Report"

        feedback = self.review_draft(draft)
        final_report = self.improve_draft(draft,feedback)

        return final_report